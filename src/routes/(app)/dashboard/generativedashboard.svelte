<!--
@file src/routes/(app)/dashboard/generativedashboard.svelte
@component
@description AI-Native Generative Dashboard Wrapper using native Svelte 5 snippets and Valibot validation.

### Features
- **AI-Native**: Renders JSON specs generated by AI agents without `json-render-svelte` / `zod`.
- **Dynamic**: Supports recursive layout trees with error boundary isolation (`<svelte:boundary>`).
- **Fallback**: Falls back to manual widget grid if no JSON spec is provided.
-->

<script lang="ts">
	import {
		sveltyRegistry,
		validateSpec,
		type Spec,
		type UIElement
	} from '@src/services/json-render/catalog';
	import type { Snippet } from 'svelte';
	import { logger } from '@utils/logger';
	import { clientJsonHeaders } from '@utils/security/client-csrf';
	import Button from '@components/ui/button.svelte';
	import Input from '@components/ui/input.svelte';
	import {
		widget_generative_title,
		widget_generative_connected,
		widget_generative_placeholder,
		widget_generative_update
	} from '@src/paraglide/messages';

	interface Props {
		spec?: Spec | null;
		context?: Record<string, unknown>;
		children?: Snippet;
	}

	let { spec = null, context: _context = {}, children }: Props = $props();

	let prompt = $state('');
	let isRegenerating = $state(false);
	let currentSpec = $state<Spec | null>(null);

	// Sync with incoming spec prop
	$effect(() => {
		if (spec) {
			currentSpec = validateSpec(spec) ?? spec;
		}
	});

	async function handleRegenerate() {
		if (!prompt.trim()) return;
		isRegenerating = true;
		try {
			const response = await fetch('/api/ai/generate-layout', {
				method: 'POST',
				headers: clientJsonHeaders(),
				body: JSON.stringify({
					prompt: prompt,
					contextRules: 'Connect to mcp.sveltycms.com for live context. Return only valid JSON.'
				})
			});
			const result = await response.json();
			if (result.spec) {
				currentSpec = validateSpec(result.spec) ?? (result.spec as Spec);
				logger.info('AI Dashboard updated via Knowledge Core.');
			}
		} catch (error) {
			logger.error('Regeneration failed:', error);
		} finally {
			isRegenerating = false;
		}
	}

	function resolveChildKeys(el: UIElement): string[] {
		return el.children ?? el.elements ?? [];
	}
</script>

{#snippet renderElement(elementKey: string, depth: number = 0)}
	{#if currentSpec && depth < 16}
		{@const element = currentSpec.elements[elementKey]}
		{#if element && element.visible !== false}
			{@const Comp = sveltyRegistry[element.type] ?? sveltyRegistry.Text}
			{@const childKeys = resolveChildKeys(element)}
			<svelte:boundary
				onerror={(err) =>
					logger.error(`[GenerativeDashboard] Render error in <${element.type}>:`, err)}
			>
				{#if childKeys.length > 0}
					<Comp {element} loading={isRegenerating}>
						{#each childKeys as childKey (childKey)}
							{@render renderElement(childKey, depth + 1)}
						{/each}
					</Comp>
				{:else}
					<Comp {element} loading={isRegenerating} />
				{/if}
			</svelte:boundary>
		{/if}
	{/if}
{/snippet}

<div class="generative-dashboard-container w-full h-full animate-fade-in relative">
	{#if currentSpec}
		<!-- AI Driven Layout Header -->
		<div class="flex flex-col gap-4 mb-6">
			<div
				class="flex items-center justify-between gap-4 p-4 rounded bg-surface-500/10 dark:bg-surface-900 border border-(--admin-border-default) shadow-sm"
			>
				<div class="flex items-center gap-3">
					<div class="bg-tertiary-500 dark:bg-primary-500 text-white p-2 rounded shadow-inner">
						<iconify-icon icon="mdi:robot-outline" width="24" class="text-white"></iconify-icon>
					</div>
					<div>
						<h3 class="font-bold text-lg leading-tight">{widget_generative_title()}</h3>
						<p class="text-xs text-(--admin-text-muted) flex items-center gap-1">
							<span class="inline-block w-2 h-2 rounded-full bg-success-500 animate-pulse"></span>
							{widget_generative_connected()}
						</p>
					</div>
				</div>

				<div class="flex-1 max-w-xl relative">
					<Input
						type="text"
						bind:value={prompt}
						placeholder={widget_generative_placeholder()}
						inputClass="pe-24 rounded-full"
						onkeydown={(e) => e.key === 'Enter' && handleRegenerate()}
					/>
					<Button
						variant="tertiary"
						onclick={handleRegenerate}
						disabled={isRegenerating}
						size="sm"
						class="absolute inset-e-1 top-1 bottom-1 px-4 rounded-full"
					>
						{#if isRegenerating}
							<iconify-icon icon="mdi:loading" class="animate-spin" width="18"></iconify-icon>
						{:else}
							{widget_generative_update()}
						{/if}
					</Button>
				</div>
			</div>
		</div>

		<!-- AI Content -->
		<div
			class="min-h-100 rounded-2xl border border-(--admin-border-default) bg-(--admin-bg-card) p-4 shadow-xl"
		>
			{#if currentSpec.root && currentSpec.elements?.[currentSpec.root]}
				{@render renderElement(currentSpec.root, 0)}
			{/if}
		</div>
	{:else if children}
		<!-- Manual Grid Fallback -->
		{@render children()}
	{/if}
</div>

<style>
